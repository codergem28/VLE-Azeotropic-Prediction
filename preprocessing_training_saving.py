# preprocessing_training_saving.py
"""Train the ANN surrogate for the NRTL ethanol-water VLE reference data.

Conventions: x1, y1 [-] mole fractions, T [K], P [bar]. The reference data is
generated by data.py from NRTL + Antoine; it is NOT experimental data.
"""

import json
import os
import random
import zipfile
from pathlib import Path

# Ask TensorFlow for deterministic kernels before it is imported, so a rerun of
# this script reproduces the same weights, and therefore the same metrics.
os.environ.setdefault('TF_DETERMINISTIC_OPS', '1')

import joblib
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import seaborn as sns
import tensorflow as tf
from sklearn.metrics import mean_absolute_error, mean_squared_error
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import MinMaxScaler, StandardScaler

# Import from ANN.py
from ANN import build_model, train_model

# Thermodynamic reference model (NRTL) used to build/validate the data and to
# plot the physically consistent bubble-temperature isobars.
from data import (
    FEATURES,
    REFERENCE_PRESSURE_BAR,
    TARGET,
    bubble_TK,
    psat_bar,
    validate_dataset,
    vapor_composition,
)

BASE_DIR = Path(__file__).resolve().parent
OUTPUT_DIR = BASE_DIR / 'ANN_BinaryVLE'
DATA_FILE = BASE_DIR / 'Data' / 'vle_data.csv'
MODEL_PATH = OUTPUT_DIR / 'ann_vle_model.h5'
PIPELINE_PATH = OUTPUT_DIR / 'preprocessing_pipeline.pkl'
CHECKPOINT_PATH = OUTPUT_DIR / 'best_model.weights.h5'
METRICS_PATH = OUTPUT_DIR / 'metrics.json'
ZIP_FILE = BASE_DIR / 'ANN_BinaryVLE.zip'

# One seed for python, numpy and TensorFlow, plus deterministic kernels: the
# reported MAE/RMSE belong to the artifacts that ship with the model.
SEED = 42
random.seed(SEED)
np.random.seed(SEED)
tf.keras.utils.set_random_seed(SEED)
tf.config.experimental.enable_op_determinism()

# Configure seaborn style
sns.set_style("whitegrid")
plt.rcParams['figure.figsize'] = (10, 6)


def load_data(csv_filepath=DATA_FILE):
    """Load the NRTL reference dataset and validate it thermodynamically.

    Validation (not clipping) is what guarantees the training targets are
    physical: every row must satisfy its own bubble-point equation.
    """
    csv_filepath = Path(csv_filepath)
    if not csv_filepath.exists():
        raise FileNotFoundError(
            f"Data file '{csv_filepath}' not found. Run data.py first."
        )
    df = pd.read_csv(csv_filepath)
    validate_dataset(df)
    return df


def preprocess_data(df, scaler_type='standard'):
    """Extract raw features/target and an *unfitted* scaler.

    The scaler is deliberately not fitted here: it must only ever see the
    training split, otherwise statistics from the validation and test sets
    leak into the features the model is trained on.
    """
    X = df[FEATURES].values
    y = df[TARGET].values

    if scaler_type == 'standard':
        scaler = StandardScaler()
    else:
        scaler = MinMaxScaler()

    preprocessing_pipeline = {
        'scaler': scaler,
        'scaler_type': scaler_type,
        'feature_names': FEATURES,
        'target_name': TARGET,
        'units': {'x1': '-', 'T': 'K', 'P': 'bar', 'y1': '-'},
        'reference_data': 'NRTL + Antoine (ethanol-water); not experimental',
    }

    return {
        'X_raw': X,
        'y': y,
        'preprocessing_pipeline': preprocessing_pipeline
    }


def split_data(X, y, test_size=0.15, val_size=0.15, random_state=42):
    """Split raw (unscaled) data into train/validation/test sets.

    Splitting happens before any scaling so the scaler is fitted on the
    training data only.
    """
    X_temp, X_test, y_temp, y_test = train_test_split(
        X, y, test_size=test_size, random_state=random_state, shuffle=True
    )
    val_size_adjusted = val_size / (1 - test_size)
    X_train, X_val, y_train, y_val = train_test_split(
        X_temp, y_temp, test_size=val_size_adjusted, random_state=random_state, shuffle=True
    )

    return {
        'X_train': X_train, 'X_val': X_val, 'X_test': X_test,
        'y_train': y_train, 'y_val': y_val, 'y_test': y_test
    }


def fit_preprocessing(splits, preprocessing_pipeline):
    """Fit the scaler on the training split only, then transform every split.

    Fitting on train and transforming validation/test with those same
    statistics is the leakage-free way to scale; the stored pipeline keeps
    the train-fitted scaler so inference matches training exactly.
    """
    scaler = preprocessing_pipeline['scaler']
    scaler.fit(splits['X_train'])

    return {
        'X_train': scaler.transform(splits['X_train']),
        'X_val': scaler.transform(splits['X_val']),
        'X_test': scaler.transform(splits['X_test']),
        'y_train': splits['y_train'],
        'y_val': splits['y_val'],
        'y_test': splits['y_test'],
    }


def nrtl_isobar(x1_grid, P_bar):
    """NRTL reference isobar: (T_bubble, y1) at an explicit pressure."""
    T_bubble = np.array([bubble_TK(float(x), P_bar) for x in x1_grid])
    y1 = np.array([vapor_composition(float(x), float(t), P_bar)
                   for x, t in zip(x1_grid, T_bubble)])
    return T_bubble, y1


def create_evaluation_plots(model, data_splits, preprocessing_pipeline, y_test_true, y_test_pred):
    # Parity plot
    plt.figure(figsize=(8, 8))
    sns.scatterplot(x=y_test_true, y=y_test_pred, alpha=0.7, s=60)
    min_val, max_val = min(y_test_true.min(), y_test_pred.min()), max(y_test_true.max(), y_test_pred.max())
    plt.plot([min_val, max_val], [min_val, max_val], 'r--', linewidth=2, label='Perfect prediction')
    plt.xlabel('NRTL reference y1 [-]')
    plt.ylabel('ANN predicted y1 [-]')
    plt.title('Parity Plot: NRTL Reference vs ANN Prediction (test split)')
    plt.legend()
    plt.axis('equal')
    plt.tight_layout()
    plt.savefig(OUTPUT_DIR / 'parity_plot.png', dpi=300, bbox_inches='tight')
    plt.close()

    # Residuals plot
    residuals = y_test_pred - y_test_true
    plt.figure(figsize=(10, 6))
    sns.scatterplot(x=y_test_true, y=residuals, alpha=0.7, s=60)
    plt.axhline(y=0, color='r', linestyle='--', linewidth=2, label='Zero residual')
    plt.xlabel('NRTL reference y1 [-]')
    plt.ylabel('Residuals: ANN - NRTL [-]')
    plt.title('Residuals Plot (test split)')
    plt.legend()
    plt.tight_layout()
    plt.savefig(OUTPUT_DIR / 'residuals_plot.png', dpi=300, bbox_inches='tight')
    plt.close()

    # y1 vs x1: an explicit isobar. The temperature of every point is the
    # NRTL bubble temperature at that (x1, P), so T and P are both defined
    # rather than "averaged" over the dataset.
    create_isobar_plot(model, data_splits, preprocessing_pipeline)


def create_isobar_plot(model, data_splits, preprocessing_pipeline,
                       P_bar=REFERENCE_PRESSURE_BAR):
    scaler = preprocessing_pipeline['scaler']
    x1_grid = np.linspace(0.0, 1.0, 201)

    T_bubble, y1_nrtl = nrtl_isobar(x1_grid, P_bar)
    X_grid = np.column_stack([
        x1_grid,
        T_bubble,
        np.full_like(x1_grid, P_bar),
    ])
    y1_ann = np.clip(model.predict(scaler.transform(X_grid), verbose=0).flatten(), 0, 1)

    X_test_raw = scaler.inverse_transform(data_splits['X_test'])
    on_isobar = np.isclose(X_test_raw[:, 2], P_bar, atol=1e-4)

    plt.figure(figsize=(10, 6))
    plt.plot(x1_grid, y1_nrtl, 'g-', linewidth=2.5, label='NRTL reference (bubble curve)')
    plt.plot(x1_grid, y1_ann, 'b--', linewidth=2, label='ANN surrogate')
    plt.plot(x1_grid, x1_grid, 'r:', linewidth=2, label='y1 = x1 (azeotrope line)')
    plt.scatter(X_test_raw[on_isobar, 0], data_splits['y_test'][on_isobar],
                color='black', s=45, alpha=0.8, label='NRTL test points on this isobar', zorder=5)
    plt.xlabel('x1 [-], ethanol liquid mole fraction')
    plt.ylabel('y1 [-], ethanol vapour mole fraction')
    plt.title(
        f'VLE isobar at P = {P_bar:.4f} bar (760 mmHg, ~1 atm)\n'
        f'dashed/dotted curves: T = NRTL bubble temperature, '
        f'{T_bubble.min():.1f}-{T_bubble.max():.1f} K'
    )
    plt.legend(loc='lower right')
    plt.grid(True, alpha=0.3)
    plt.xlim(0, 1)
    plt.ylim(0, 1)
    plt.tight_layout()
    plt.savefig(OUTPUT_DIR / 'y_vs_x_plot.png', dpi=300, bbox_inches='tight')
    plt.close()


def plot_training_history(history):
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(15, 5))
    ax1.plot(history.history['loss'], label='Training Loss')
    ax1.plot(history.history['val_loss'], label='Validation Loss')
    ax1.set_xlabel('Epoch'); ax1.set_ylabel('MSE Loss'); ax1.set_title('Training and Validation Loss')
    ax1.legend(); ax1.grid(True, alpha=0.3)

    ax2.plot(history.history['mae'], label='Training MAE')
    ax2.plot(history.history['val_mae'], label='Validation MAE')
    ax2.set_xlabel('Epoch'); ax2.set_ylabel('Mean Absolute Error'); ax2.set_title('Training and Validation MAE')
    ax2.legend(); ax2.grid(True, alpha=0.3)

    plt.tight_layout()
    plt.savefig(OUTPUT_DIR / 'training_history.png', dpi=300, bbox_inches='tight')
    plt.close()


def evaluate_model(model, data_splits, preprocessing_pipeline):
    y_test_pred = model.predict(data_splits['X_test'], verbose=0).flatten()
    y_test_true = data_splits['y_test']
    y_test_pred = np.clip(y_test_pred, 0, 1)

    mae = mean_absolute_error(y_test_true, y_test_pred)
    rmse = np.sqrt(mean_squared_error(y_test_true, y_test_pred))

    create_evaluation_plots(model, data_splits, preprocessing_pipeline, y_test_true, y_test_pred)

    return {'mae': float(mae), 'rmse': float(rmse)}


def implement_raoult_baseline(data_splits, preprocessing_pipeline):
    """Ideal-solution (Raoult's law, all gamma_i = 1) reference.

    Why this baseline: it uses the *same* Antoine correlations and the same
    (x1, T, P) as the NRTL reference data, and drops only the activity
    coefficients. The gap between it and the NRTL curve therefore isolates
    exactly the non-ideality that the surrogate has to learn, which is what
    makes it a meaningful floor for the ANN.

    The values are reported unclipped: where Raoult's law predicts y1 > 1 it
    is simply outside its validity, which is the well-known failure of the
    ideal assumption for ethanol-water.
    """
    scaler = preprocessing_pipeline['scaler']
    X_test_raw = scaler.inverse_transform(data_splits['X_test'])

    x1_test = X_test_raw[:, 0]
    T_test = X_test_raw[:, 1]
    P_test = X_test_raw[:, 2]

    # Antoine, same correlation as the reference model, converted mmHg -> bar.
    P_sat1_bar = psat_bar('ethanol', T_test - 273.15)
    y1_baseline = (x1_test * P_sat1_bar) / P_test

    y_test_true = data_splits['y_test']
    mae_baseline = mean_absolute_error(y_test_true, y1_baseline)
    rmse_baseline = np.sqrt(mean_squared_error(y_test_true, y1_baseline))
    outside = float(np.mean(y1_baseline > 1.0))

    plt.figure(figsize=(8, 8))
    sns.scatterplot(x=y_test_true, y=y1_baseline, alpha=0.7, s=60, color='orange')
    upper = max(1.05, float(y1_baseline.max()))
    plt.plot([0, upper], [0, upper], 'r--', linewidth=2, label='Perfect prediction')
    plt.xlabel('NRTL reference y1 [-]')
    plt.ylabel("Raoult's law y1 [-], gamma_i = 1")
    outside_note = (f"; {outside * 100:.0f}% of points give unphysical y1 > 1"
                    if outside > 0 else "")
    plt.title(
        "Ideal-solution baseline (Raoult's law, same Antoine fit, same T and P)\n"
        f"MAE = {mae_baseline:.4f}{outside_note}"
    )
    plt.legend(); plt.axis('equal')
    plt.xlim(0, upper); plt.ylim(0, upper)
    plt.tight_layout()
    plt.savefig(OUTPUT_DIR / 'baseline_parity_plot.png', dpi=300, bbox_inches='tight')
    plt.close()

    return {
        'mae_baseline': float(mae_baseline),
        'rmse_baseline': float(rmse_baseline),
        'fraction_y1_above_1': outside,
    }


def save_artifacts(model, preprocessing_pipeline):
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    model.save(MODEL_PATH)
    joblib.dump(preprocessing_pipeline, PIPELINE_PATH)


def create_results_zip():
    files_to_zip = [
        'ann_vle_model.h5',
        'preprocessing_pipeline.pkl',
        'best_model.weights.h5',
        'metrics.json',
        'parity_plot.png',
        'residuals_plot.png',
        'y_vs_x_plot.png',
        'training_history.png',
        'baseline_parity_plot.png',
    ]
    with zipfile.ZipFile(ZIP_FILE, 'w') as zipf:
        for file in files_to_zip:
            path = OUTPUT_DIR / file
            if path.exists():
                zipf.write(path, arcname=file)
    return ZIP_FILE


def main():
    # train_model writes the checkpoint into this directory, so create it up front
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

    EPOCHS = 200
    BATCH_SIZE = 32
    LEARNING_RATE = 0.001
    SCALER_TYPE = 'standard'

    df = load_data(DATA_FILE)

    # Split first, then scale: the scaler is fitted on the training split only
    # so validation/test statistics cannot leak into training.
    data_final = preprocess_data(df, SCALER_TYPE)
    splits_raw = split_data(data_final['X_raw'], data_final['y'])
    splits_final = fit_preprocessing(splits_raw, data_final['preprocessing_pipeline'])
    pipeline = data_final['preprocessing_pipeline']

    # Domain of validity, taken from the training split, so inference can warn
    # about extrapolation instead of silently returning garbage.
    pipeline['feature_ranges'] = {
        name: [float(splits_raw['X_train'][:, i].min()),
               float(splits_raw['X_train'][:, i].max())]
        for i, name in enumerate(FEATURES)
    }

    model = build_model((len(FEATURES),), LEARNING_RATE)
    model, history = train_model(
        model,
        splits_final['X_train'], splits_final['y_train'],
        splits_final['X_val'], splits_final['y_val'],
        epochs=EPOCHS, batch_size=BATCH_SIZE, patience=20,
        checkpoint_path=str(CHECKPOINT_PATH),
    )

    plot_training_history(history)
    save_artifacts(model, pipeline)

    evaluation_results = evaluate_model(model, splits_final, pipeline)
    baseline_results = implement_raoult_baseline(splits_final, pipeline)

    metrics = {
        'reference_data': 'NRTL + Antoine ethanol-water (not experimental)',
        'units': {'x1': '-', 'T': 'K', 'P': 'bar', 'y1': '-'},
        'scaler_type': SCALER_TYPE,
        'n_train': int(len(splits_raw['X_train'])),
        'n_val': int(len(splits_raw['X_val'])),
        'n_test': int(len(splits_raw['X_test'])),
        'test_mae': evaluation_results['mae'],
        'test_rmse': evaluation_results['rmse'],
        'baseline_mae': baseline_results['mae_baseline'],
        'baseline_rmse': baseline_results['rmse_baseline'],
        'baseline_fraction_y1_above_1': baseline_results['fraction_y1_above_1'],
        'mae_improvement_factor': (
            baseline_results['mae_baseline'] / evaluation_results['mae']
            if evaluation_results['mae'] > 0 else None
        ),
    }
    METRICS_PATH.write_text(json.dumps(metrics, indent=2), encoding='utf-8')

    create_results_zip()

    print('Training complete.')
    print(f"  test MAE  : {metrics['test_mae']:.6f}")
    print(f"  test RMSE : {metrics['test_rmse']:.6f}")
    print(f"  baseline MAE (Raoult, gamma=1): {metrics['baseline_mae']:.6f}")
    print(f"  improvement over baseline: {metrics['mae_improvement_factor']:.1f}x")
    print(f"  metrics written to {METRICS_PATH}")


if __name__ == "__main__":
    main()
